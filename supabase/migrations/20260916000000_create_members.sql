-- ALOM 운영진(members) 테이블 생성 + 시드 데이터
-- Supabase 대시보드 > SQL Editor 에 전체를 붙여넣고 실행하세요.

create table if not exists public.members (
  id text primary key,
  name text not null,
  position text not null,
  student_id text not null,
  department text not null,
  created_at timestamptz not null default now()
);

alter table public.members enable row level security;

-- 아직 Supabase Auth 연동 전이라 anon key로 조회 가능하게 열어둡니다.
-- 실제 서비스 전환 시 인증된 운영진만 읽도록 정책을 좁혀주세요.
drop policy if exists "members are publicly readable" on public.members;
create policy "members are publicly readable"
  on public.members for select
  to anon, authenticated
  using (true);

